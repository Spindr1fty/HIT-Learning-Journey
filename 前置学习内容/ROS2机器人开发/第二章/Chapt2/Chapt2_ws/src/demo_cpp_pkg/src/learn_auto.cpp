#include <iostream>
using namespace std;
int main()
{
    auto x = 5;     // int x = 5;
    auto y1 = 3.14;  // double y = 3.14;
    auto y2 = 3.14f; // float y = 3.14;
    auto z = 'a';   // char z = a;
    cout << x << endl;
    cout << y1 << endl;
    cout << y2 << endl;
    cout << z << endl;
    return 0;
}